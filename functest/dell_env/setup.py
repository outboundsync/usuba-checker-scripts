#!/usr/bin/env python3
"""Build the Dell-faithful Omarchy runtime used by runtime.py (idempotent).
  /opt/ft/omarchy-dell : basecamp/omarchy @ OMARCHY_COMMIT (= Omarchy 4.0.0.alpha, whose shell/ tree is verified byte-identical to
                         /usr/share/omarchy/shell on a reference Omarchy laptop, see omarchy-shell-ref.tar.gz) + the harness ftProbe IPC fn;
                         bin/ pruned to the Dell's real /usr/share/omarchy/bin list (omarchy_bins.txt)
  /opt/ft/themes/<t>   : theme dirs generated by the real omarchy-theme-set-templates (colors.toml + shell.toml)
  /opt/ft/shims-dell   : PATH for the sandbox = one logging shim per executable that exists on the Dell (omarchy_bins + system_bins);
                         anything else is simply not on PATH, so Quickshell reports "Process failed to start" exactly like the Dell.
"""
import os, subprocess, shutil, tarfile, hashlib, sys, tempfile, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from binaries import KNOWN, OMARCHY_BINS
OMARCHY_COMMIT = "c668141e9c42b13c80c9ca4ea108e11708c5e8a5"
GIT = os.environ.get("FT_OMARCHY_GIT", "/opt/ft/omarchy-git")
DST, THEMES, SHIMS = os.environ.get("FT_OMARCHY", "/opt/ft/omarchy-4.0.4"), "/opt/ft/themes", "/opt/ft/shims-dell"
THEME_LIST = ("catppuccin-latte", "tokyo-night")
STAMP = os.path.join(DST, ".ft-stamp")

def _check_dst(path):
    """The build rmtree()s DST: refuse anything that is not clearly an omarchy build dir (audit C3: FT_OMARCHY=$HOME must not be wiped)."""
    rp = os.path.realpath(path)
    if rp in ("/", os.path.realpath(os.path.expanduser("~"))) or not os.path.basename(rp).startswith("omarchy") or rp.count("/") < 2:
        raise SystemExit("refusing to build into %r: FT_OMARCHY must name a dedicated directory called omarchy*" % path)
    return path
_check_dst(DST)

def _tree_digest(h, root):
    for r, ds, fs in os.walk(root):
        ds.sort()
        for f in sorted(fs):
            p = os.path.join(r, f)
            h.update(os.path.relpath(p, root).encode())
            h.update(os.readlink(p).encode() if os.path.islink(p) else open(p, "rb").read())

def stamp():
    """Everything a rebuild depends on: this dir, the in-repo reference tree and the fixtures (audit D8: they were not in the stamp)."""
    h = hashlib.sha1()
    for f in sorted(os.listdir(HERE)):
        if f.endswith((".py", ".txt", ".part", ".gz", ".sh")): h.update(f.encode()); h.update(open(os.path.join(HERE, f), "rb").read())
    for extra in (os.path.join(HERE, "../../dell-ref/omarchy-4.0.4"), os.path.join(HERE, "../fixtures")):
        if os.path.isdir(extra): _tree_digest(h, os.path.normpath(extra))
    return h.hexdigest()

SHIM = r'''#!/bin/bash
n=${0##*/}
if [ -n "$FT_EXECLOG" ]; then
  pc=; read -r pc < /proc/$PPID/comm 2>/dev/null
  rec="S"$'\t'"$$"$'\t'"$pc"$'\t'"$n"; for a in "$@"; do a=${a//$'\t'/ }; rec+=$'\t'"${a//$'\n'/\\n}"; done
  printf '%s\n' "$rec" >> "$FT_EXECLOG" 2>/dev/null
fi
if [ "$n" = hyprctl ]; then /usr/bin/python3 "$FT_HYPRCTL" "$@"; rc=$?
else
  real=; IFS=: read -ra _d <<< "$FT_REALPATH"; for d in "${_d[@]}"; do [ -x "$d/$n" ] && { real="$d/$n"; break; }; done
  [ "$n" = awk ] && [ -x /usr/bin/gawk ] && real=/usr/bin/gawk   # Arch awk is gawk (box default is mawk)
  if [ -n "$real" ]; then "$real" "$@"; rc=$?; else rc=0; fi   # exists on the Dell, not in the box: behave like an idle tool
fi
[ -n "$FT_EXECLOG" ] && printf 'E\t%s\t%s\n' "$$" "$rc" >> "$FT_EXECLOG" 2>/dev/null
exit $rc
'''

FULL_REF = os.environ.get("FT_DELL_FULL", os.path.join(HERE, "../../dell-ref/omarchy-4.0.4"))   # /usr/share/omarchy from the Dell on 4.0.4-1 (images excluded; extracted from omarchy-4.0.4-tree.tar.gz)   # full /usr/share/omarchy from the Dell

def build():
    import fcntl
    if os.path.exists(STAMP) and open(STAMP).read() == stamp(): return
    os.makedirs("/opt/ft", exist_ok=True)
    with open("/opt/ft/.build.lock", "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        if os.path.exists(STAMP) and open(STAMP).read() == stamp(): return
        _build()

def _build():
    tmp = DST + ".tmp"; shutil.rmtree(tmp, ignore_errors=True); os.makedirs(tmp)
    if not os.path.isdir(GIT):
        subprocess.run(["git", "clone", "-q", "https://github.com/basecamp/omarchy", GIT], check=True)
    arc = subprocess.run(["git", "-C", GIT, "archive", OMARCHY_COMMIT], check=True, capture_output=True).stdout   # no shell, no string-built command (audit C3)
    import io
    with tarfile.open(fileobj=io.BytesIO(arc)) as t: t.extractall(tmp, filter="data")
    # verify against the Dell's real shell tree
    ref = tempfile.mkdtemp()
    with tarfile.open(os.path.join(HERE, "omarchy-shell-ref.tar.gz")) as t: t.extractall(ref, filter="data")
    r = subprocess.run(["diff", "-rq", os.path.join(ref, "shell"), os.path.join(tmp, "shell")], capture_output=True, text=True)
    if r.returncode != 0: raise SystemExit("omarchy shell at commit differs from the Dell reference:\n" + r.stdout[:2000])
    shutil.rmtree(ref)
    for b in os.listdir(os.path.join(tmp, "bin")):
        if b not in OMARCHY_BINS: os.remove(os.path.join(tmp, "bin", b))
    if os.path.isdir(FULL_REF):   # every shipped file must match the Dell's full install (only repo-only files may differ)
        # bin/ on the Dell is symlinks into /usr/bin (packaged layout, contents not captured): compare the name set only
        if set(os.listdir(os.path.join(FULL_REF, "bin"))) != set(os.listdir(os.path.join(tmp, "bin"))):
            raise SystemExit("bin/ name set differs from the Dell")
        for sub in [s for s in ("shell", "default", "config", "themes", "install", "migrations", "applications") if os.path.isdir(os.path.join(FULL_REF, s))]:
            r = subprocess.run(["diff", "-rq", "--no-dereference", os.path.join(FULL_REF, sub), os.path.join(tmp, sub)], capture_output=True, text=True)
            bad = [l for l in r.stdout.splitlines() if not l.startswith("Only in " + tmp)]
            if bad: raise SystemExit(f"{sub}/ differs from the Dell's /usr/share/omarchy:\n" + "\n".join(bad[:20]))
    sq = os.path.join(tmp, "shell/shell.qml"); s = open(sq).read()
    i = s.rstrip().rfind("}"); j = s.rstrip()[:i].rstrip().rfind("}")
    s = s[:j] + open(os.path.join(HERE, "ftprobe.qml.part")).read() + s[j:]
    open(sq, "w").write(s)
    shutil.rmtree(DST, ignore_errors=True); os.rename(tmp, DST)
    # themes via the real template generator
    for t in THEME_LIST:
        H = tempfile.mkdtemp(); N = os.path.join(H, ".local/state/omarchy/current/next-theme"); os.makedirs(N)
        src = os.path.join(DST, "themes", t)
        for f in os.listdir(src):
            if os.path.isfile(os.path.join(src, f)) and not f.endswith(".png"): shutil.copy(os.path.join(src, f), N)
        subprocess.run(["bash", os.path.join(DST, "bin/omarchy-theme-set-templates")], env=dict(os.environ, HOME=H, OMARCHY_PATH=DST,
                       PATH=f"{DST}/bin:/usr/bin:/bin"), check=True, capture_output=True)
        shutil.rmtree(os.path.join(THEMES, t), ignore_errors=True); shutil.copytree(N, os.path.join(THEMES, t)); shutil.rmtree(H)
    shutil.rmtree(SHIMS, ignore_errors=True); os.makedirs(SHIMS)
    for n in sorted(KNOWN):
        if "/" in n or n in (".", "..", "["): continue
        p = os.path.join(SHIMS, n); open(p, "w").write(SHIM); os.chmod(p, 0o755)
    # reference replacement bar = the stock 4.0.0.alpha bar packaged as a third-party bar plugin. Hot-swapping to ANY bar makes the
    # stock shell's own weather/power/network panels log "Cannot read property 'foreground' of null" (Omarchy bug, seen on the
    # Dell too); runtime.py subtracts what this reference bar triggers so only plugin-caused breakage counts.
    rb = "/opt/ft/refbar"; shutil.rmtree(rb, ignore_errors=True); shutil.copytree(os.path.join(DST, "shell/plugins/bar"), rb)
    m = json.load(open(os.path.join(rb, "manifest.json"))); m.update(id="ft.refbar", name="Reference bar"); json.dump(m, open(os.path.join(rb, "manifest.json"), "w"), indent=1)
    open(STAMP, "w").write(stamp())

if __name__ == "__main__":
    build(); print("ok", DST)
